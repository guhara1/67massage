INSERT_MARK = '<section class="section" style="padding-top:30px">'

def main():
    base = os.path.join(os.path.dirname(__file__), "areas")
    changed = 0
    for path in sorted(glob.glob(os.path.join(base, "*.html"))):
        slug = os.path.splitext(os.path.basename(path))[0]
        if slug not in R:
            print("SKIP (no data):", slug); continue
        html = open(path, encoding="utf-8").read()
        if 'id="price"' in html:
            print("SKIP (already done):", slug); continue
        data = dict(R[slug]); data["extra"] = EXTRA[slug]
        guide = GUIDE_TMPL.format(**data)
        block = "\n" + PRICE_HTML + "\n" + guide + "\n"
        new = html.replace(INSERT_MARK, block + INSERT_MARK, 1)
        if new == html:
            print("WARN: marker not found:", slug); continue
        open(path, "w", encoding="utf-8").write(new)
        changed += 1
        print("OK:", slug)
    print("changed:", changed)

if __name__ == "__main__":
    main()
